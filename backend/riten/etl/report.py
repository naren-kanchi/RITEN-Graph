"""Write the data-quality report for the latest successful batch to Markdown."""
from pathlib import Path

import psycopg


def write_report(dsn: str, path: Path) -> None:
    with psycopg.connect(dsn) as conn:
        row = conn.execute(
            "SELECT batch_id, finished_at, data_version, row_counts FROM import_batch "
            "WHERE status = 'succeeded' ORDER BY batch_id DESC LIMIT 1").fetchone()
        if row is None:
            raise RuntimeError("no successful import batch")
        batch_id, finished, version, counts = row
        rules = conn.execute(
            """SELECT severity, rule, source_file, COUNT(*), (array_agg(COALESCE(source_id || ': ', '') || detail ORDER BY issue_id))[1:3]
               FROM etl_issue WHERE batch_id = %s GROUP BY severity, rule, source_file ORDER BY severity, COUNT(*) DESC""",
            (batch_id,)).fetchall()
    lines = [
        "# Data quality report", "",
        "Generated by `python -m riten.etl.run --report`. Do not edit by hand.", "",
        f"- Batch: {batch_id}", f"- Finished: {finished:%Y-%m-%d %H:%M %Z}", f"- Data version: `{version}`", "",
        "## Source reconciliation", "",
        "| File | Rows | Synthetic |", "|---|---:|---:|",
    ]
    for name, c in counts["raw"].items():
        lines.append(f"| `{name}` | {c['rows']:,} | {c['synthetic']:,} |")
    lines += ["| **Total** | **{:,}** | **{:,}** |".format(
        sum(c["rows"] for c in counts["raw"].values()), sum(c["synthetic"] for c in counts["raw"].values())), ""]
    lines += ["## Canonical tables", "", "| Table | Rows |", "|---|---:|"]
    lines += [f"| `{t}` | {n:,} |" for t, n in counts["canonical"].items()]
    lines += ["", f"Total: {sum(counts['canonical'].values()):,} rows, including dimension tables.", ""]
    lines += ["## Disclosed caveats", "",
              "These are properties of the source. They were recorded and left unchanged.", "",
              "| Rule | File | Rows | Examples |", "|---|---|---:|---|"]
    if not rules:
        lines.append("| none | | | |")
    for severity, rule, source_file, n, examples in rules:
        text = "<br>".join(str(e).replace("|", "/") for e in examples)
        lines.append(f"| `{rule}` | {source_file} | {n} | {text} |")
    lines += ["", "No blocking rule fired: a blocking failure rolls back the whole batch and is recorded against it.", ""]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines), encoding="utf-8")
